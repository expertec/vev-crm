import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { CONTRACTS } from './contracts.mjs';

function ts(schema) {
  if (schema.anyOf) return schema.anyOf.map(ts).join(' | ');
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(x => JSON.stringify(x)).join(' | ');
  if (schema.type === 'object') return `{ ${Object.entries(schema.properties).map(([key, value]) => `${JSON.stringify(key)}${schema.required.includes(key) ? '' : '?'}: ${ts(value)};`).join(' ')} }`;
  if (schema.type === 'array') return `Array<${ts(schema.items)}>`;
  return ({ integer: 'number', number: 'number', string: 'string', boolean: 'boolean', null: 'null' })[schema.type];
}
export function artifacts() {
  return {
    ...Object.fromEntries(Object.entries(CONTRACTS).map(([name, schema]) => [`schema/${name}.schema.json`, `${JSON.stringify(schema, null, 2)}\n`])),
    'types.d.ts': '// Generated by export-contracts.mjs. Runtime semantic validation is also mandatory.\n' + Object.entries(CONTRACTS).map(([name, schema]) => `export type ${name} = ${ts(schema)};\n`).join(''),
  };
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const checkOnly = process.argv.includes('--check');
  for (const [name, text] of Object.entries(artifacts())) {
    const path = new URL(name, import.meta.url);
    if (checkOnly) {
      if (await readFile(path, 'utf8') !== text) throw new Error(`Contract drift: ${name}`);
    } else { await mkdir(new URL('.', path), { recursive: true }); await writeFile(path, text); }
  }
  console.log(checkOnly ? 'Contracts and types match source' : 'Exported 5 schemas and TypeScript types');
}
